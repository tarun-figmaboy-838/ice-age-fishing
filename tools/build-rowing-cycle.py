#!/usr/bin/env python3
"""Pre-renders Popo's paddling cycle into one small WebP sheet the game plays back.

The articulated rig in src/rowing.js deforms a 1280px mesh; doing that every frame while
rowing cost 20-120 ms a frame (and much more from file://, where WebGL can't read the art).
This renders the cycle once with the same rig, crops every frame to the union of the
figure, scales it to the size the game shows it at, and writes:
  assets/sprites/popo-row-cycle.webp   the frames, in a grid
  src/rowing-cycle-data.js             PopoGame.ROWING_CYCLE: grid, frame size, seat point
The game crossfades between neighbouring frames, so the motion stays continuous.

Requires Python Playwright + Chromium and Pillow. Run after tools/build-rowing.py:
  python3 tools/build-rowing-cycle.py
"""
import base64
import io
import json
import math
from pathlib import Path

from PIL import Image
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
FRAMES = 24
COLUMNS = 6
SCALE = 0.42   # atlas px per rig px; the game draws the rig at 0.21 stage px per rig px
MARGIN = 6


def data_url(path):
    return 'data:image/png;base64,' + base64.b64encode(path.read_bytes()).decode()


def rig_data():
    text = (ROOT / 'src/rowing-data.js').read_text()
    start = text.index('{', text.index('ROWING_RIG'))
    return json.loads(text[start:text.rindex('}') + 1])


def main():
    data = rig_data()
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        page = browser.new_page()
        page.goto('about:blank')
        page.evaluate((ROOT / 'src/rowing.js').read_text())
        frames = page.evaluate('''async ({ body, paddle, data, count }) => {
          const load = async (src) => { const im = new Image(); im.src = src; await im.decode(); return im; };
          const rig = new PopoGame.PaddleRig(await load(body), await load(paddle), data);
          const out = [];
          for (let i = 0; i < count; i += 1) {
            const c = document.createElement('canvas');
            c.width = data.frameSize[0]; c.height = data.frameSize[1];
            const g = c.getContext('2d');
            g.translate(...data.frameOrigin);
            rig.draw(g, (i / count) * data.cycleMs, data.cycleMs);
            out.push(c.toDataURL('image/png').split(',')[1]);
          }
          return out;
        }''', {'body': data_url(ROOT / 'assets/sprites/paddling/body.png'),
               'paddle': data_url(ROOT / 'assets/sprites/paddling/paddle.png'),
               'data': data, 'count': FRAMES})
        browser.close()

    images = [Image.open(io.BytesIO(base64.b64decode(f))).convert('RGBA') for f in frames]
    boxes = [im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox() for im in images]
    x0 = max(0, min(b[0] for b in boxes) - MARGIN)
    y0 = max(0, min(b[1] for b in boxes) - MARGIN)
    x1 = max(b[2] for b in boxes) + MARGIN
    y1 = max(b[3] for b in boxes) + MARGIN
    w, h = math.ceil((x1 - x0) * SCALE), math.ceil((y1 - y0) * SCALE)
    rows = math.ceil(FRAMES / COLUMNS)
    atlas = Image.new('RGBA', (w * COLUMNS, h * rows), (0, 0, 0, 0))
    for i, im in enumerate(images):
        cell = im.crop((x0, y0, x1, y1)).resize((w, h), Image.LANCZOS)
        atlas.alpha_composite(cell, ((i % COLUMNS) * w, (i // COLUMNS) * h))
    out = ROOT / 'assets/sprites/popo-row-cycle.webp'
    atlas.save(out, 'WEBP', quality=90, method=6)

    # where the rig's seat lands inside a frame, in atlas px
    seat = [(data['seat'][0] + data['frameOrigin'][0] - x0) * SCALE,
            (data['seat'][1] + data['frameOrigin'][1] - y0) * SCALE]
    meta = {'frames': FRAMES, 'columns': COLUMNS, 'width': w, 'height': h, 'scale': SCALE,
            'seat': [round(seat[0], 2), round(seat[1], 2)]}
    (ROOT / 'src/rowing-cycle-data.js').write_text(
        '// Generated by tools/build-rowing-cycle.py: the pre-rendered paddling cycle.\n'
        'window.PopoGame = window.PopoGame || {};\n'
        f'PopoGame.ROWING_CYCLE = {json.dumps(meta)};\n')
    print(f'{FRAMES} frames of {w}x{h} -> {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)')


if __name__ == '__main__':
    main()
